#include "meta_model.hpp"

#include <cctype>
#include <set>
#include <sstream>
#include <string>

namespace {

  std::string sanitizeUri(const std::string& uri) {
    std::string out;

    for (const char ch : uri) {
      if (std::isalnum(static_cast<unsigned char>(ch))) {
        out.push_back(ch);
      } else {
        out.push_back('_');
      }
    }

    return out;
  }

}

namespace telar::qt_moc {

  std::string emitQmlMeta(const UnitMeta& unit) {
    std::ostringstream out;

    out << "module " << primaryModuleName(unit.module_name) << "\n";
    for (const auto& cls : unit.classes) {
      if (!cls.qml_exposed) {
        continue;
      }

      out << (cls.is_namespace ? "namespace " : "class ") << cls.qualified_name << "\n";
      if (cls.inherits_quick_item) {
        out << "quick_item 1\n";
      }

      for (const auto& en : cls.enums) {
        out << "enum " << en.qualified_name << "\n";
      }
    }

    return out.str();
  }

  UnitMeta parseQmlMeta(const std::string& text) {
    UnitMeta out;
    std::istringstream in(text);
    std::string line;

    while (std::getline(in, line)) {
      if (line.empty()) {
        continue;
      }

      if (line.starts_with("module ")) {
        out.module_name = line.substr(7);
      } else if (line.starts_with("class ") || line.starts_with("namespace ")) {
        ClassMeta cls;

        cls.module_name = out.module_name;
        cls.is_namespace = line.starts_with("namespace ");
        cls.qualified_name = line.substr(cls.is_namespace ? 10 : 6);
        cls.qml_exposed = true;
        out.classes.push_back(std::move(cls));
      } else if (line == "quick_item 1" && !out.classes.empty()) {
        out.classes.back().inherits_quick_item = true;
      } else if (line.starts_with("enum ") && !out.classes.empty()) {
        EnumMeta en;

        en.qualified_name = line.substr(5);
        out.classes.back().enums.push_back(std::move(en));
      }
    }

    return out;
  }

  std::string emitQmlRegistrations(const std::vector<UnitMeta>& units, const std::string& qt_module, const std::string& uri, int major, int minor) {
    std::set<std::string> modules;
    bool any_quick_item = false;

    for (const auto& unit : units) {
      for (const auto& cls : unit.classes) {
        if (cls.qml_exposed) {
          const auto primary = primaryModuleName(cls.module_name);
          if (!primary.empty()) {
            modules.insert(primary);
          }

          any_quick_item = any_quick_item || cls.inherits_quick_item;
        }
      }
    }

    std::ostringstream out;

    out << "// Generated by telar-moc (QML type registration via C++23 modules).\n";
    out << "import " << qt_module << ";\n";
    for (const auto& mod : modules) {
      out << "import " << mod << ";\n";
    }

    const auto symbol = sanitizeUri(uri);

    out << "\nvoid qml_register_types_" << symbol << "() {\n";
    if (any_quick_item) {
      out << "  qmlRegisterAnonymousType<QQuickItem, 254>(\"" << uri << "\", " << major << ");\n";
    }

    for (const auto& unit : units) {
      for (const auto& cls : unit.classes) {
        if (!cls.qml_exposed) {
          continue;
        }

        if (cls.is_namespace) {
          out << "  {\n";
          out << "    constinit static auto meta_type = QQmlPrivate::metaTypeForNamespace(\n";
          out << "        [](const QtPrivate::QMetaTypeInterface*) { return &" << cls.qualified_name << "::staticMetaObject; },\n";
          out << "        \"" << cls.qualified_name << "\");\n";
          out << "    QMetaType(&meta_type).id();\n";
          out << "  }\n";
          out << "  qmlRegisterNamespaceAndRevisions(&" << cls.qualified_name << "::staticMetaObject, \"" << uri << "\", " << major << ", nullptr, &" << cls.qualified_name << "::staticMetaObject, nullptr);\n";
        } else {
          out << "  qmlRegisterTypesAndRevisions<" << cls.qualified_name << ">(\"" << uri << "\", " << major << ");\n";
        }

        for (const auto& en : cls.enums) {
          out << "  qmlRegisterEnum<" << en.qualified_name << ">(\"" << en.qualified_name << "\");\n";
        }
      }
    }

    out << "  qmlRegisterModule(\"" << uri << "\", " << major << ", " << minor << ");\n";
    out << "}\n\n";
    out << "static const QQmlModuleRegistration registration_" << symbol << "(\"" << uri << "\", qml_register_types_" << symbol << ");\n";
    return out.str();
  }

}
